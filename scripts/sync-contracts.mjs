#!/usr/bin/env node
// Copies compiled ABIs and deployed factory addresses from contracts/ into the app.
// Run after `arc-forge build` (ABIs) and after `arc-forge script ... --broadcast` (addresses).
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'contracts', 'out');
const broadcast = join(root, 'contracts', 'broadcast', 'Deploy.s.sol');
const target = join(root, 'app', 'src', 'lib', 'contracts', 'generated.ts');

const CHAINS = { testnet: 5042002, mainnet: 5042 };

function abiOf(file, name) {
  const path = join(out, file, `${name}.json`);
  if (!existsSync(path)) throw new Error(`Missing ${path}. Run "arc-forge build" in contracts/ first.`);
  return JSON.parse(readFileSync(path, 'utf8')).abi;
}

function deploymentOf(chainId) {
  const path = join(broadcast, String(chainId), 'run-latest.json');
  if (!existsSync(path)) return null;
  const run = JSON.parse(readFileSync(path, 'utf8'));
  const tx = run.transactions.find((t) => t.transactionType === 'CREATE' && t.contractName === 'GroupWalletFactory');
  if (!tx) return null;
  const receipt = run.receipts.find((r) => r.transactionHash === tx.hash);
  return {
    factory: tx.contractAddress,
    deployBlock: receipt ? Number(BigInt(receipt.blockNumber)) : 0,
    txHash: tx.hash,
  };
}

const deployments = Object.fromEntries(
  Object.entries(CHAINS).map(([network, chainId]) => [network, deploymentOf(chainId)]),
);

const banner = '// AUTO-GENERATED by scripts/sync-contracts.mjs. Do not edit by hand.\n';
const body =
  banner +
  `export const groupWalletAbi = ${JSON.stringify(abiOf('GroupWallet.sol', 'GroupWallet'), null, 2)} as const;\n\n` +
  `export const groupWalletFactoryAbi = ${JSON.stringify(
    abiOf('GroupWalletFactory.sol', 'GroupWalletFactory'),
    null,
    2,
  )} as const;\n\n` +
  `export const deployments: Record<'testnet' | 'mainnet', { factory: \`0x\${string}\`; deployBlock: number; txHash: string } | null> = ${JSON.stringify(
    deployments,
    null,
    2,
  )};\n`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, body);
console.log(`Wrote ${target}`);
for (const [network, d] of Object.entries(deployments)) {
  console.log(`  ${network}: ${d ? `${d.factory} (block ${d.deployBlock})` : 'not deployed'}`);
}
